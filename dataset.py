def build_dataframe() -> pd.DataFrame:
    rows: list[dict[str, str]] = []
    for label, lines in [
        ("calm", CALM),
        ("stressed", STRESSED),
        ("anxious", ANXIOUS),
        ("lonely", LONELY),
        ("overwhelmed", OVERWHELMED),
        ("crisis", CRISIS),
    ]:
        for text in lines:
            rows.append({"text": text.strip(), "label": label})
    return pd.DataFrame(rows)
